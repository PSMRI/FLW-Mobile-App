// Joins src/*.js (sorted by name) into code.js — Figma plugins need one main file.
// Usage: node build.js
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, 'src');
// embed audit data (design/audit/*.json) for the complete-spec stages
const audit = path.join(__dirname, '..', 'audit');
if (fs.existsSync(path.join(audit, 'forms.json'))) {
  const forms = JSON.parse(fs.readFileSync(path.join(audit, 'forms.json'), 'utf8')).filter((d) => d.fields.length);
  const cards = JSON.parse(fs.readFileSync(path.join(audit, 'cards.json'), 'utf8'));
  fs.writeFileSync(path.join(dir, '25-audit-data.js'), '// GENERATED from design/audit/*.json by build.js\nconst AUDIT_FORMS = ' + JSON.stringify(forms) + ';\nconst AUDIT_CARDS = ' + JSON.stringify(cards) + ';\n');
}
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js')).sort();
const out = ['// GENERATED by build.js from src/ — edit the files in src/, not this file.\n']
  .concat(files.map((f) => `// ===== ${f} =====\n` + fs.readFileSync(path.join(dir, f), 'utf8')));
fs.writeFileSync(path.join(__dirname, 'code.js'), out.join('\n'));
console.log('code.js built from: ' + files.join(', '));
